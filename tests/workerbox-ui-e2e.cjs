'use strict';
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { webcrypto } = require('node:crypto');
const errors = [];
(async () => {
const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
try {
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 const response=await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
 assert.equal(response.status(),200,'Local page must load');
 assert.match(await page.title(),/Rhodium Germany/i);
 assert.equal(await page.locator('#kundenpakete article.card').count(),6,'Exactly 6 customer packages');
 await page.getByRole('link',{name:/Eigene Datei kostenlos testen/i}).first().click();
 assert.equal(new URL(page.url()).hash,'#gratis-test');
 await page.locator('#gratis-file').setInputFiles({name:'synthetic.bin',mimeType:'application/octet-stream',buffer:Buffer.from('Rhodium Workerbox | public synthetic free trial')});
 await page.locator('#gratis-run').click();
 await page.locator('#gratis-report:not([hidden])').waitFor({timeout:15000});
 assert.match(await page.locator('#gratis-report').innerText(),/Bitidentische lokale Kopie: PASS/);
 assert.match(await page.locator('#gratis-report').innerText(),/Gezielte Manipulation erkannt: PASS/);
 assert.match(await page.locator('#gratis-report').innerText(),/GZIP-Roundtrip: PASS/);
 assert.match(await page.locator('#gratis-status').innerText(),/^PASS:/);
 assert.equal(await page.locator('#gratis-copy').isDisabled(),false);
 await page.locator('#gratis-reset').click();
 assert.equal(await page.locator('#gratis-report').isVisible(),false);
 await page.locator('#gratis-file').setInputFiles({name:'large.bin',mimeType:'application/octet-stream',buffer:Buffer.alloc(20*1024*1024+1)});
 await page.locator('#gratis-run').click();
 assert.match(await page.locator('#gratis-status').innerText(),/maximal 20 MiB/);
 await page.locator('#gratis-file').setInputFiles({name:'empty.bin',mimeType:'application/octet-stream',buffer:Buffer.alloc(0)});
 await page.locator('#gratis-run').click();
 await page.locator('#gratis-report:not([hidden])').waitFor({timeout:15000});
 assert.match(await page.locator('#gratis-report').innerText(),/Gesamtergebnis: PASS/);
 await page.locator('#demo-equal').click();
 assert.match(await page.locator('#demo-status').innerText(),/^PASS:/);
 await page.locator('#demo-changed').click();
 assert.match(await page.locator('#demo-status').innerText(),/^PASS:/);
 const keyPair=await webcrypto.subtle.generateKey({name:'RSA-PSS',modulusLength:2048,publicExponent:new Uint8Array([1,0,1]),hash:'SHA-256'},true,['sign','verify']);
 const original='synthetic release for browser E2E only';
 const sig=Buffer.from(await webcrypto.subtle.sign({name:'RSA-PSS',saltLength:32},keyPair.privateKey,Buffer.from(original))).toString('base64');
 const der=Buffer.from(await webcrypto.subtle.exportKey('spki',keyPair.publicKey));
 const pem='-----BEGIN PUBLIC KEY-----\\n'+der.toString('base64').match(/.{1,64}/g).join('\\n')+'\\n-----END PUBLIC KEY-----';
 await page.locator('#rsa-original').fill(original);
 await page.locator('#rsa-signature').fill(sig);
 await page.locator('#rsa-public').fill(pem);
 await page.locator('#rsa-verify').click();
 await page.locator('#rsa-result').getByText(/PASS:/).waitFor();
 await page.locator('#rsa-original').fill(original+' modified');
 await page.locator('#rsa-verify').click();
 await page.locator('#rsa-result').getByText(/FAIL:/).waitFor();
 await page.locator('#rsa-original').fill('');
 await page.locator('#rsa-verify').click();
 await page.locator('#rsa-result').getByText(/KEIN NACHWEIS:/).waitFor();
 await page.locator('[data-offer="Integrität & Nachweise"]').first().click();
 assert.equal(await page.locator('#selected-offer').inputValue(),'Integrität & Nachweise');
 await page.locator('#area').fill('Testrechenzentrum');
 await page.locator('#problem').fill('Synthetische Testdaten');
 await page.locator('#outcome').fill('Prüfbericht');
 await page.locator('#contact').fill('Tester – kein echter Kunde');
 await page.locator('#copy').click();
 assert.match(await page.locator('#form-status').innerText(),/kopiert|nicht möglich/i);
 await page.setViewportSize({width:360,height:740});
 assert.equal(await page.locator('#gratis-test').isVisible(),true);
 assert.deepEqual(errors,[],'No uncaught JavaScript errors');
 console.log(JSON.stringify({result:'PASS',scope:'LOCAL_BROWSER_E2E',mobile:true,tests:['6-packages','navigation','file-hash','tamper','gzip-roundtrip','size-limit','empty-file','reset','synthetic-demo','RSA-PSS-positive','RSA-PSS-negative','RSA-PSS-missing','offer-select','inquiry','mobile-viewport','no-js-errors'],real_workerbox:false,real_customer_transfer:false}));
} finally {await browser.close()}
})().catch(e=>{console.error('E2E FAIL:',e.stack||e);process.exitCode=1});
